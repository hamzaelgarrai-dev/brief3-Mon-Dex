export const getData = async () => {
  try {

    const res = await fetch("https://db.ygoprodeck.com/api/v7/cardinfo.php?num=12&offset=12");
    const data = await res.json();

    return data.data;

  } catch (error) {
    console.log(error)
    return [];
  }
};

